#!/usr/bin/env bash
# Boot the `jeromy` dsh profile with this repo's plugin mounted from source
# (roadmap item 1). Writes a --patch overlay with absolute paths into
# .dsh-dev/ (gitignored), then runs the harness checkout's CLI under tsx so
# .ts plugin files load directly.
#
# Env: DSH_SRC   harness checkout (default ../deepseek-harness)
#      DSH_PORT  web UI port (default 3080)
#      DSH_MODEL model id (default deepseek-flash)
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
DSH_SRC="$(cd "${DSH_SRC:-$REPO/../deepseek-harness}" && pwd)"
PORT="${DSH_PORT:-3080}"
MODEL="${DSH_MODEL:-deepseek-flash}"
mkdir -p "$REPO/.dsh-dev"
PATCH="$REPO/.dsh-dev/cordis.yml"
cat > "$PATCH" <<YAML
# Generated by scripts/dsh-dev.sh. Dev overlay for the jeromy profile.
- insert:
    - id: jeromy
      name: '$REPO/src/dsh/index.ts'
      config:
        port: 9001
        requestTimeout: 15000
- id: agent-default-model
  config:
    provider: deepseek-official
    model: $MODEL
    reasoningEffort: low
# Emulator view page lives in the right-sidebar browser (ADR-0004); off by default in web profiles.
- id: ui-sidebar-browser
  disabled: false
# Do not upload the session log (prompt, tool results, clicks) to DeepSeek's API
# with each request; dsh's shipped profiles default this on (ADR-0011).
- id: session-log-deepseek
  config:
    enabled: false
# A ROM-hacking model should not be offered the coding-agent toolbelt (ADR-0001).
- id: tool-bash
  disabled: true
- id: tool-pwsh
  disabled: true
- id: tool-fs
  disabled: true
- id: tool-fs-search
  disabled: true
YAML
"$REPO/scripts/link-dsh.sh" >/dev/null
echo "[dsh-dev] profile jeromy · patch $PATCH · http://127.0.0.1:$PORT"
# Always mirror output to .dsh-dev/dsh.log so scripts/up.sh can find the web
# URL (with its token) however dsh was started.
cd "$DSH_SRC" && pnpm dsh --profile jeromy --patch "$PATCH" --port "$PORT" "$@" 2>&1 | tee -a "$REPO/.dsh-dev/dsh.log"

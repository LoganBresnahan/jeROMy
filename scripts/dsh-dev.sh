#!/usr/bin/env bash
# Boot the `jeromy` dsh profile with this repo's plugin mounted from source
# (roadmap item 1). Writes a --patch overlay with absolute paths into
# .dsh-dev/ (gitignored), then runs the harness checkout's CLI under tsx so
# .ts plugin files load directly.
#
# Env: DSH_SRC   harness checkout (default ../deepseek-harness)
#      DSH_PORT  web UI port (default 3080)
#      DSH_MODEL model id (default deepseek-flash)
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
DSH_SRC="$(cd "${DSH_SRC:-$REPO/../deepseek-harness}" && pwd)"
PORT="${DSH_PORT:-3080}"
MODEL="${DSH_MODEL:-deepseek-flash}"
mkdir -p "$REPO/.dsh-dev"
PATCH="$REPO/.dsh-dev/cordis.yml"
cat > "$PATCH" <<YAML
# Generated by scripts/dsh-dev.sh. Dev overlay for the jeromy profile.
- insert:
    - id: jeromy
      name: '$REPO/src/dsh/index.ts'
      config:
        port: 9001
        requestTimeout: 15000
- id: agent-default-model
  config:
    provider: deepseek-official
    model: $MODEL
    reasoningEffort: low
# Emulator view page lives in the right-sidebar browser (ADR-0004); off by default in web profiles.
- id: ui-sidebar-browser
  disabled: false
# Do not upload the session log (prompt, tool results, clicks) to DeepSeek's API
# with each request; dsh's shipped profiles default this on (ADR-0011).
- id: session-log-deepseek
  config:
    enabled: false
# A ROM-hacking model should not be offered the coding-agent toolbelt (ADR-0001).
# Host rows (what headless runs see):
- id: tool-bash
  disabled: true
- id: tool-pwsh
  disabled: true
- id: tool-fs
  disabled: true
- id: tool-fs-search
  disabled: true
# Web app: tools are per agent preset, so the toolbelt is a preset (roadmap
# item 11, Logan 2026-10-05: keep a read-only shell and read_image, drop
# write/edit/fs search, subagents, workflows, plan mode, web). The jeROMy
# tools themselves are host rows from the plugin above and reach every preset.
- id: agent-preset-registry
  config:
    default: jeromy
# "Read-only shell": tool-fs has no per-tool switch, so the sandbox carries
# the rule. Fresh sessions start read-only; the person can still pick
# workspace-write or danger-full-access in the UI (config is replaced
# wholesale, so the preset table is restated).
- id: permission
  config:
    defaultPreset: read-only
    presets:
      read-only:
        sandbox: read-only
        approval: ask
      workspace-write:
        sandbox: workspace-write
        approval: ask
      danger-full-access:
        sandbox: danger-full-access
        approval: never
- insert:
    - id: preset-jeromy
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: jeromy
        order: 0
        name: jeROMy
        description: ROM hacking against the live emulator; shell for pixel math only
        plugins:
          - id: persona
            name: '@deepseek-ai/dsh-persona'
            config:
              prefix: >-
                You are jeROMy on the {{model}} model. Work through the emulator tools; the shell is for image and pixel arithmetic, never for editing files.
          - id: time-context
            name: '@deepseek-ai/dsh-time-context'
          - id: tool-bash
            name: '@deepseek-ai/dsh-tool-bash'
            config:
              enableRunInBackground: false
          - id: tool-fs
            name: '@deepseek-ai/dsh-tool-fs'
          - id: skill-filesystem
            name: '@deepseek-ai/dsh-skill-filesystem'
          - id: tool-skill
            name: '@deepseek-ai/dsh-tool-skill'
          - id: tool-ask-user
            name: '@deepseek-ai/dsh-tool-ask-user'
          - id: present
            name: '@deepseek-ai/dsh-tool-present'
          - id: compaction
            name: cordis:group
            group: true
            isolate:
              compaction: true
              toolResultPruner: true
            config:
              - id: compaction-basic
                name: '@deepseek-ai/dsh-compaction-basic'
              - id: command-compact
                name: '@deepseek-ai/dsh-command-compact'
              - id: tool-result-pruner
                name: '@deepseek-ai/dsh-compaction-tool-result-pruner'
                config:
                  thresholdChars: 8192
YAML
"$REPO/scripts/link-dsh.sh" >/dev/null
echo "[dsh-dev] profile jeromy · patch $PATCH · http://127.0.0.1:$PORT"
# Always mirror output to .dsh-dev/dsh.log so scripts/up.sh can find the web
# URL (with its token) however dsh was started.
cd "$DSH_SRC" && pnpm dsh --profile jeromy --patch "$PATCH" --port "$PORT" "$@" 2>&1 | tee -a "$REPO/.dsh-dev/dsh.log"
